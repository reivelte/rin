    template <typename T>
    concept is_descriptor = requires
    {
        requires std::derived_from<T, query_descriptor>;
    };
    /* ******* special query commands use concept uris *******
        concept://!taglist
        concept://!taglist/similar_to/{id}
        concept://!taglist/{id}
        concept://!filelist/{id phrase}

        - where {id phrase} is a valid query string (ex. 'cat, dog | bird')
          note that standalone {id} is a valid query phrase too
          id must refer to an entity registered in the database

        - note that concept entities with ids beginning with '!' are reserved for internal use
    */

    /* ******* uris refer directly to entries at their source *******
        // get info on the entity referenced by the given id
        index://{id}

        file://{path to file}   // reference a place on the local filesystem
        index://{path to file}  // reference a database entry representing a local file
        index://{path to concept script} // get metadata on a registered concept script

        // reference a resource at some external location
        https://{ip address or domain name}

        // reference a resource generated by a predefined concept script
        concept://{path to concept script}/{params}

        - where {path to concept script} is an id referencing
          a concept script registered in the database and {params}
          are arguments to the script (separated with commas, ex: 'cat, dog, bird')
    */
    
    enum class query_source : i8
    {
        None = 0x0,
        Concept = 0x1,
        External = 0x2,
        Filesystem = 0x4,
        Index = 0x6
    };
    enum class query_status : i8 {
        Invalid = 0, Initializing, In_Progress, Completed, Paused, Canceled
    };
    enum class descriptor_type : i8 { Query, Index, Concept, Thumbnail };

    // describes the result and function of reading/writing from/to
    // one or more designated sources, as well as the nodes
    // of the entity tree which are a result of reading from said sources
    struct query_descriptor
    {
        public:
        usize file_size = 0;
        usize dir_count = 0;
        usize file_count = 0;
        usize tag_count = 0;
        usize concept_count = 0;
        query_source source = query_source::None;
        query_status status = query_status::Invalid;
        std::optional<std::tuple<Qt::SortOrder, entity_attribute_type>> sort_info = std::nullopt;
        std::optional<entity_tree_keymap> keymap;

        query_descriptor();
        query_descriptor(const QString& uri);

        template <is_descriptor D>
        query_descriptor& operator+=(const D& rhs);

        template <is_descriptor D>
        query_descriptor& operator-=(const D& rhs);

        inline query_descriptor& operator+=(const reflexive_entity& e);
        inline query_descriptor& operator-=(const reflexive_entity& e);

        inline void set_uri(const QString& uri);
        inline void set_size(usize x) noexcept;

        template <is_descriptor D>
        void adjust(const D& d, bool increment);

        void adjust(const reflexive_entity& e, bool increment);

        inline QString uri() const noexcept;
        inline QString text() const noexcept;
        inline sz::entity_type uri_type() const noexcept;
        inline usize size() const noexcept { return m_size; }

        protected:
        friend class entity_data_manager;
        friend class reflexive_descriptor;
        usize processed = 0; // dataman only or when using operator +=/-= between two descriptors

        private:
        QString m_uri;
        sz::entity_type m_uri_type = sz::entity_type::Invalid;
        usize m_size = 0;
    };

    #define query_descriptor_impl using base = query_descriptor; using base::base

    // describes the result and function of reading/writing from/to the index
    struct index_descriptor : public query_descriptor, public index_parameters
    {
        query_descriptor_impl;
        using aux = index_parameters;
        using aux::aux;

        index_descriptor()
        {
            source = query_source::Index;
        }
    };

    // describes the result and function of reading/writing from/to
    // arbitrary locations, including from concept entities
    struct concept_descriptor : public query_descriptor
    {
        query_descriptor_impl;
        struct parameters
        {
            enum action : u32
            {
                Ignore = 0x0,
                Copy = Qt::DropAction::CopyAction, // 0x1 : 00000001
                Move = Qt::DropAction::MoveAction, // 0x2 : 00000010
                Link = Qt::DropAction::LinkAction, // 0x4 : 00000100
                Remove = 0x6, // 00001000
                Recycle = 0x8 // 00010000
            };
        };
        
        QList<QString> uris;
        parameters::action act = parameters::action::Ignore;

        concept_descriptor()
        {
            source = query_source::Concept;
        }
    };

    // describes the result and function of reading/writing thumbnails
    struct thumbnail_descriptor : public query_descriptor
    {
        query_descriptor_impl;
        QPixmap thumbnail;
        QString entity_name;
        QSize original_size; // see entity.Sizehint
        sz::thumbnail_target_size target_size;
        sz::entity_type entity_type;
        data_node_key node_key;
    };

    typedef std::variant<
        query_descriptor,
        index_descriptor,
        concept_descriptor,
        thumbnail_descriptor
    > descriptor_variant;

    class reflexive_descriptor : public descriptor_variant
    {
        using base = descriptor_variant;
        using base::base;

        public:
        // template <typename Func> requires (sz::is_function_of<Func, sz::result<usize>, std::string_view, query_source>)
        // static sz::result<reflexive_descriptor> from_uri(const QString& uri, Func size_func);

        reflexive_descriptor(const query_descriptor& qd) : base(qd), m_type(Query) {}
        reflexive_descriptor(const index_descriptor& qd) : base(qd), m_type(Index) {}
        reflexive_descriptor(const concept_descriptor& qd) : base(qd), m_type(Concept) {}
        reflexive_descriptor(const thumbnail_descriptor& qd) : base(qd), m_type(Thumbnail) {}

        inline operator query_descriptor&() { return std::get<query_descriptor>(*this); }
        inline operator index_descriptor&() { return std::get<index_descriptor>(*this); }
        inline operator concept_descriptor&() { return std::get<concept_descriptor>(*this); }
        inline operator thumbnail_descriptor&() { return std::get<thumbnail_descriptor>(*this); }

        reflexive_descriptor& operator+=(const reflexive_entity& e);
        reflexive_descriptor& operator-=(const reflexive_entity& e);

        void set_uri(QString uri);
        void set_status(query_status s);
        void set_sort_info(entity_attribute_type sort_key, Qt::SortOrder sort_order);
        void set_size(usize s);
        void set_processed_count(usize count);
        void clear() noexcept;

        QString uri() const noexcept;
        QString text() const noexcept;
        query_source source() const noexcept;
        sz::entity_type uri_type() const noexcept;
        query_status status() const noexcept;
        std::optional<std::tuple<Qt::SortOrder, entity_attribute_type>> sort_info() const noexcept;
        usize size() const noexcept;
        usize processed_count() const noexcept;
        inline descriptor_type type() const noexcept { return m_type; }

        private:
        using enum descriptor_type;
        template <typename T> T& m_get();
        template <typename T> const T& m_get() const;
        descriptor_type m_type;
    };

    template <is_descriptor D>
    inline query_descriptor& query_descriptor::operator+=(const D& rhs)
    {
        adjust(rhs, true);
        return *this;
    }

    template <is_descriptor D>
    inline query_descriptor& query_descriptor::operator-=(const D& rhs)
    {
        adjust(rhs, false);
        return *this;
    }

    inline query_descriptor& query_descriptor::operator+=(const reflexive_entity& e)
    {
        adjust(e, true);
        return *this;
    }

    inline query_descriptor& query_descriptor::operator-=(const reflexive_entity& e)
    {
        adjust(e, false);
        return *this;
    }

    inline void query_descriptor::set_uri(const QString& uri)
    {
        m_uri = uri;
        m_uri_type = std::get<1>(sz::id_from_uri(uri.toStdString()));
    }

    inline void query_descriptor::set_size(usize x) noexcept
    {
        m_size = x;
    }

    template <is_descriptor D>
    inline void query_descriptor::adjust(const D& d, bool increment)
    {
        std::array<std::tuple<usize*, usize>, 6> elems{
            {&processed, d.processed},
            {&file_size, d.file_size},
            {&dir_count, d.dir_count},
            {&file_count, d.file_count},
            {&tag_count, d.tag_count},
            {&concept_count, d.concept_count}
        };

        for (auto& [out, x] : elems)
        {
            if (increment) {
                *out += x;
            }
            else if (!increment && (x < *out)) {
                *out -= x;
            }
        }
    }

    inline QString query_descriptor::uri() const noexcept
    {
        return m_uri;
    }

    inline QString query_descriptor::text() const noexcept
    {
        const std::string uri_ = m_uri.toStdString();
        std::string_view id = std::get<0>(sz::id_from_uri(uri_));
        return QString::fromUtf8(id.data(), id.size());
    }

    inline sz::entity_type query_descriptor::uri_type() const noexcept
    {
        return m_uri_type;
    }

